import os
import re
import logging
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import StrOutputParser

logger = logging.getLogger(__name__)

class CodeFixAgent:
    """
    Agent responsible for generating smart code fixes using LangChain and Gemini.
    """
    
    def __init__(self):
        api_key = os.getenv("GEMINI_API_KEY")
        if not api_key:
            raise ValueError("GEMINI_API_KEY is missing from .env")
            
        # Swap out OpenAI for Gemini 1.5 Flash
        self.llm = ChatGoogleGenerativeAI(
            model="gemini-2.5-flash", 
            google_api_key=api_key,
            temperature=0
        )
        
    def create_fix_prompt(self, bug_description: str = "", current_code: str = "") -> PromptTemplate:
        """
        Builds the explicit prompt template formatted as strictly requested.
        Parameters are primarily included for structural completeness if you need to inspect inputs dynamically,
        but the primary function yields the static template wrapper.
        """
        template = """You are a senior software engineer. Fix this bug.
Current code:
{current_code}

Bug report: {bug_description}

Return ONLY the fixed code without any markdown formatting (do not use javascript or jsx), no explanations, and no commentary. Start directly with the code."""

        return PromptTemplate(
            template=template,
            input_variables=["current_code", "bug_description"]
        )

    def generate_fix(self, bug_description: str, current_code: str) -> str:
        """
        Creates the LCEL pipeline chain, queries the core LLM, and returns its direct response.
        
        Args:
            bug_description (str): Textual description defining the bug context.
            current_code (str): The raw string contents of the buggy original file.
            
        Returns:
            str: The raw generated completion output from the LLM.
        """
        prompt = self.create_fix_prompt()
        
        # Modern LCEL syntax
        chain = prompt | self.llm | StrOutputParser()
        
        logger.info("Invoking LangChain CodeFixAgent LCEL pipeline...")
        raw_response = chain.invoke({
            "bug_description": bug_description,
            "current_code": current_code
        })
        
        return raw_response

    def extract_code_from_response(self, llm_response: str) -> str:
        """
        Aggressively removes any possible trailing or wrapping Markdown features that the LLM may 
        have mistakenly injected despite being instructed not to.
        
        Args:
            llm_response (str): The raw string generated by the LLM.
            
        Returns:
            str: Only the pure, executable code string.
        """
        cleaned_response = llm_response.strip()
        
        # Standard block match: ```[optional_language_tag] ... ```
        match = re.search(r"^```[a-zA-Z]*\n?(.*?)\n?```$", cleaned_response, re.DOTALL | re.IGNORECASE)
        
        if match:
            cleaned_response = match.group(1).strip()
            logger.info("Regex captured and stripped markdown backticks.")
        else:
            # Aggressive fallback logic trimming trailing backticks manually just in case
            if cleaned_response.startswith("```"):
                # Try isolating the lines below the ticks (usually the first line has the language tag)
                first_newline_idx = cleaned_response.find("\n")
                if first_newline_idx != -1:
                    cleaned_response = cleaned_response[first_newline_idx:].strip()
                else:
                    # if literally placed sequentially with no spacing
                    cleaned_response = cleaned_response.lstrip("`").strip()
                    
            if cleaned_response.endswith("```"):
                cleaned_response = cleaned_response.rstrip("`").strip()

        return cleaned_response
